// Post-build step: writes out/sw.js with a precache list of every file in the
// static export, versioned by a content hash so each deploy gets a fresh cache.
import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = path.resolve("out");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])),
  );
  return files.flat();
}

const files = (await walk(OUT))
  .map((f) => "/" + path.relative(OUT, f).split(path.sep).join("/"))
  .filter((url) => url !== "/sw.js" && !url.endsWith(".map"))
  .sort();

const hash = createHash("sha256");
for (const url of files) hash.update(url).update(await readFile(path.join(OUT, url)));
const version = hash.digest("hex").slice(0, 12);

// "/index.html" is cached under "/" too so navigations resolve offline.
const precache = ["/", ...files.filter((u) => u !== "/index.html")];

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const CACHE = "my-wants-${version}";
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;

  // Pages: network first so updates arrive, cached shell when offline.
  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((res) => {
          if (res.ok) caches.open(CACHE).then((c) => c.put("/", res.clone()));
          return res;
        })
        .catch(() => caches.match("/")),
    );
    return;
  }

  // Assets: cache first; fingerprinted files never change.
  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then(
      (cached) =>
        cached ||
        fetch(request).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(request, copy));
          }
          return res;
        }),
    ),
  );
});
`;

await writeFile(path.join(OUT, "sw.js"), sw);
console.log(`sw.js: ${precache.length} files precached, cache ${version}`);
